"""Generate vectors.inc: compact C table for the Rosetta x87 probe.

Reads re/out/x87/corpus.jsonl (regenerate via gen_vectors.py) and emits a
subset: every logical vector's full cell set is kept for the game-config
relevant ops; for size, we keep ALL logical vectors (2713) but only the
cells the referee needs:
  - fadd/fsub/fmul/fdiv/fsqrt: all 12 PCxRC cells (PC effect is the point)
  - others: all 5 cells (4 RC at PC64 + PC24 witness)
i.e. the full corpus. 21,702 rows x ~40 bytes = ~870KB include. Fine.

Row encoding (C struct, 40 bytes):
  uint16 id; uint8 op; uint8 pc; uint8 rc; uint8 tag_pad;
  int8 a_sign; uint8 a_kind (0=num 1=zero 2=inf 3=nan); int16 a_exp; uint64 a_sig;
  int8 b_sign; uint8 b_kind; int16 b_exp; uint64 b_sig; int32 pad;
op enum: 0=fadd 1=fsub 2=fmul 3=fdiv 4=fsqrt 5=fsin 6=fcos 7=f2xm1 8=fyl2x
         9=fpatan 10=fprem 11=fcom 12=fcomp 13=fucom 14=fucomi 15=fld 16=fst 17=fistp
"""
from __future__ import annotations

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
CORPUS = os.path.abspath(os.path.join(HERE, "..", "out", "x87", "corpus.jsonl"))
OUT = os.path.join(HERE, "rosetta", "vectors.inc")

OPS = ["fadd", "fsub", "fmul", "fdiv", "fsqrt", "fsin", "fcos", "f2xm1",
       "fyl2x", "fpatan", "fprem", "fcom", "fcomp", "fucom", "fucomi",
       "fld", "fst", "fistp"]


def enc_op(o: dict):
    """Return (sign, kind, exp, sig). kind: 0=num 1=zero 2=inf 3=nan."""
    s = o["sign"]
    e = o.get("exp")
    if isinstance(e, str):
        k = {"zero": 1, "inf": 2, "nan": 3}[e]
        return s, k, 0, o["sig"] & 0xFFFFFFFFFFFFFFFF
    if "biased" in o:
        return s, 0, int(o["biased"]) - 16383, o["sig"] & 0xFFFFFFFFFFFFFFFF
    return s, 0, int(e), o["sig"] & 0xFFFFFFFFFFFFFFFF


def main() -> None:
    rows = [json.loads(l) for l in open(CORPUS)]
    with open(OUT, "w") as f:
        f.write("/* generated by gen_subset.py from corpus.jsonl; do not edit */\n")
        f.write(f"/* rows: {len(rows)} */\n")
        f.write("static const struct vec ROWS[] = {\n")
        for r in rows:
            a = enc_op(r["a"])
            if r.get("b") is None:
                b = (0, 1, 0, 0)  # zero placeholder, unused
            else:
                b = enc_op(r["b"])
            opi = OPS.index(r["op"])
            f.write(f"{{{r['id']},{opi},{r['pc']},{r['rc']},"
                    f"{a[0]},{a[1]},{a[2]},0x{a[3]:016x}ULL,"
                    f"{b[0]},{b[1]},{b[2]},0x{b[3]:016x}ULL}},\n")
        f.write("};\n")
        f.write(f"static const int NROWS = {len(rows)};\n")
    print(f"wrote {len(rows)} rows -> {OUT}")


if __name__ == "__main__":
    main()
