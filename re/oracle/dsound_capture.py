#!/usr/bin/env python3
"""Capture the headless original's semantic DirectSound call stream (G7/S6).

Runs `StreetLegal_Redline.bak.exe` under the existing strict Unicorn startup
oracle with the declared boot platform profile, attaches
`re/headless/dsound_trace.py`, and writes into `re/out/headless/audio/<label>/`:

    dsound.jsonl   header + one canonical event per IDirectSound* call
    manifest.json  provenance: exe/profile/source identities, limit, stop, counts

The stream is evidence only for the scenario it ran (declared headless sound
device, virtual clock); it says nothing about physical audio. A run that stops
on a Boundary keeps the events recorded so far and says so in the manifest.

    ~/slr-oracle-venv/bin/python re/oracle/dsound_capture.py --label boot-2100M --limit 2100000000
"""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import re
import json
import subprocess
import sys
import time
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "re/headless"))


OUT = REPO / "re/out/headless/audio"
HEADLESS = REPO / "re/out/headless"
DEFAULT_DESKTOP = HEADLESS / "window-transcript-native/hypothetical-seven-notifications-declared-handle-profile.json"
DEFAULT_MEDIA = HEADLESS / "hypothetical-cd-toc.json"
DEFAULT_GRAPHICS = HEADLESS / "boot/graphics-profile.json"


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def git(*args: str) -> str:
    return subprocess.run(["git", "-C", str(REPO), *args], check=True, capture_output=True, text=True).stdout.strip()


def source_identity() -> dict:
    spec = importlib.util.spec_from_file_location("audio_capture_diagnostics", REPO / "re/boot-diagnose.py")
    diagnostics = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(diagnostics)
    return diagnostics.git_identity(REPO)[0]


def output_directory(label: str) -> Path:
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_-]{0,63}", label):
        raise ValueError("capture label must be a single simple directory name")
    output = (OUT / label).resolve()
    if not output.is_relative_to(REPO.resolve() / "re/out/headless/audio"):
        raise ValueError("audio output must be inside this worktree's re/out/headless/audio")
    if output.exists() and any(output.iterdir()):
        raise ValueError("refusing to reuse a nonempty capture directory")
    return output


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--label", required=True, help="output directory name under re/out/headless/audio/")
    ap.add_argument("--limit", type=int, default=2_100_000_000)
    ap.add_argument("--exe", type=Path, default=REPO / "reference/raw/StreetLegal_Redline.bak.exe")
    ap.add_argument("--platform-profile", type=Path, help="default: generated by make_boot_profile.py into the output directory")
    ap.add_argument("--graphics-profile", type=Path, default=DEFAULT_GRAPHICS)
    ap.add_argument("--desktop-profile", type=Path, default=DEFAULT_DESKTOP)
    ap.add_argument("--media-profile", type=Path, default=DEFAULT_MEDIA)
    ap.add_argument("--fast-count", action="store_true", default=True)
    args = ap.parse_args()

    out_dir = output_directory(args.label)
    if sha256(args.exe) != "7d77466a8c1a34d16a59d9ccf2e8059664dff1bfb421338074a461a932e8edde":
        raise ValueError("original executable identity mismatch")
    if args.limit <= 0:
        raise ValueError("instruction limit must be positive")
    import startup
    from dsound_trace import SCHEMA, DirectSoundTrace
    from graphics import GraphicsProfile
    from desktop import DesktopProfile
    from media import MediaProfile
    from platform_profile import PlatformProfile
    out_dir.mkdir(parents=True, exist_ok=True)
    platform_path = args.platform_profile
    if platform_path is None:
        platform_path = out_dir / "platform-profile.json"
        subprocess.run([sys.executable, str(REPO / "re/headless/make_boot_profile.py"), str(platform_path)], check=True, capture_output=True)
    source_before = source_identity()
    inputs = {"exe": args.exe, "platform": platform_path, "graphics": args.graphics_profile, "desktop": args.desktop_profile, "media": args.media_profile}
    inputs_before = {name: sha256(path) for name, path in inputs.items()}
    runner = startup.Startup(
        args.exe,
        media_profile=MediaProfile.load(args.media_profile),
        graphics_profile=GraphicsProfile.load(args.graphics_profile),
        desktop_profile=DesktopProfile.load(args.desktop_profile),
        platform_profile=PlatformProfile.load(platform_path),
        calllog_path=None,
        observe_dir=startup.scratch_output(out_dir / "observed"),
        record_limit=100000,
        event_ring=5000,
        fast_count=args.fast_count,
    )
    identity = {
        "exe_sha256": runner.exe_sha256,
        "platform_profile_sha256": sha256(platform_path),
        "graphics_profile_sha256": sha256(args.graphics_profile),
        "desktop_profile_sha256": sha256(args.desktop_profile),
        "media_profile_sha256": sha256(args.media_profile),
        "instruction_limit": args.limit,
        "oracle": "headless original under Unicorn (re/headless/startup.py)",
        "scenario": "declared boot profile; no scripted input",
    }
    trace = DirectSoundTrace(runner, out_dir / "dsound.jsonl", startup.Boundary, provenance=identity)
    trace.attach_create(runner)
    started = time.time()
    result = runner.run(args.limit)
    trace.close()
    manifest = {
        "schema": SCHEMA,
        "label": args.label,
        "events": trace.events,
        "instructions": result["instructions"],
        "stop": result["stop"],
        "wall_seconds": round(time.time() - started, 1),
        "identity": identity,
        "source": source_before,
        "source_after": source_identity(),
        "inputs_before": inputs_before,
        "inputs_after": {name: sha256(path) for name, path in inputs.items()},
        "dsound_jsonl_sha256": sha256(out_dir / "dsound.jsonl"),
        "physical_sound_observed": False,
    }
    manifest["stale"] = manifest["source"] != manifest["source_after"] or manifest["inputs_before"] != manifest["inputs_after"]
    (out_dir / "manifest.json").write_text(json.dumps(manifest, indent=1, sort_keys=True) + "\n")
    print(json.dumps({k: manifest[k] for k in ("events", "instructions", "stop", "wall_seconds")}))
    return 2 if manifest["stale"] else 0


if __name__ == "__main__":
    raise SystemExit(main())
