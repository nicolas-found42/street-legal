#!/usr/bin/env python3
"""Transcribe487f20's256 identical MOV/PUSH/CALL declarations as source data.

The generated addresses describe original native registration instructions;
they are not an ABI admission list and no implementation result is supplied.
"""
from pathlib import Path
import hashlib,struct
ROOT=Path(__file__).resolve().parents[2]
def declarations(start=0x487f20,end=0x489e20):
 data=(ROOT/'reference/raw/StreetLegal_Redline.bak.exe').read_bytes()
 assert hashlib.sha256(data).hexdigest()=='7d77466a8c1a34d16a59d9ccf2e8059664dff1bfb421338074a461a932e8edde'
 u=lambda offset:struct.unpack_from('<I',data,offset)[0]
 pe=u(0x3c);optional=struct.unpack_from('<H',data,pe+20)[0];table=pe+24+optional
 sections=[struct.unpack_from('<8sIIII',data,table+40*i)for i in range(struct.unpack_from('<H',data,pe+6)[0])]
 def read(address,n):
  for name,virtual,rva,size,offset in sections:
   if rva<=address-0x400000 and address-0x400000+n<=rva+size:return data[offset+address-0x400000-rva:offset+address-0x400000-rva+n]
  raise ValueError(hex(address))
 result=[]
 pc=start
 while end is None or pc<end:
  if end is None and read(pc,1)==b'\xc3':break
  code=read(pc,31);cursor=0;pushes=[];ecx_after=None
  while cursor<31:
   if code[cursor:cursor+6]==b'\x8b\x0d\x1c\x64\x63\0':
    assert ecx_after is None;ecx_after=len(pushes);cursor+=6
   elif code[cursor]==0x68:
    pushes.append(struct.unpack_from('<I',code,cursor+1)[0]);cursor+=5
   elif code[cursor]==0xe8:
    assert cursor==26 and len(pushes)==4 and ecx_after is not None
    assert pc+31+struct.unpack_from('<i',code,27)[0]==0x416b00
    cursor+=5
   else:raise ValueError((hex(pc+cursor),code.hex()))
  result.append((pc+31,pushes[::-1],ecx_after));pc+=31
 if end is not None:assert len(result)==(end-start)//31
 return result
if __name__=='__main__':
 output=ROOT/'crates/slr-boot/src/native_vm_registry_catalog.rs'
 lines=['//! Generated by re/oracle/native_vm_registry_catalog.py from build606.', '//! Original caller return PCs and registration arguments; never ABI admission.', 'pub(super) const DECLARATIONS: [(u32, [u32; 4], usize); 256] = [']
 lines += ['    (0x%06x, [%s], %d),'%(pc,', '.join('0x%06x'%a for a in args),ecx_after)for pc,args,ecx_after in declarations()]
 output.write_text('\n'.join(lines+ ['];','']))
 print(output)
 secondary=ROOT/'crates/slr-boot/src/native_vm_registry_secondary_catalog.rs'
 lines=['//! Additional source registration callers; generated by native_vm_registry_catalog.py.', '//! Static instruction operands, never native-result data or ABI admission.']
 counts=[]
 for start,name in [(0x46b530,'VEHICLE'),(0x4427e0,'PART')]:
  rows=declarations(start,None);counts.append(len(rows))
  lines.append('pub(super) const %s: [(u32, [u32;4],usize);%d] = ['%(name,len(rows)))
  lines += ['    (0x%06x, [%s], %d),'%(pc,', '.join('0x%06x'%a for a in args),ecx_after)for pc,args,ecx_after in rows]
  lines.append('];')
 assert sum(counts)+256==353
 secondary.write_text('\n'.join(lines+['']))
 print(secondary,counts)
