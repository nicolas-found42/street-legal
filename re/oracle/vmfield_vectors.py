def typed_cell(sc, kind, ty, word, name=None):
    p=sc._cell({'k':kind,'t':ty[0] if ty[0] in TC else 'L','w':word})
    if ty not in ('I','F','L;'): sc.o.write_u32(p+4,cstr(sc.o,ty))
    if kind=='var' and name is not None: sc.o.write_u32(p+12,cstr(sc.o,name))
    return p

def owner_cells(sc,cells):
    obj=sc.o.alloc(20);container=sc.o.alloc(16);sc._container_set(container,cells);sc.o.write_u32(obj+12,container)
    return obj

def cell_value(o,p):
    return {'type':o.read_cstr(o.read_u32(p+4)).decode(),'word':o.read_u32(p+8)}

def stack_values(sc,frame,locations):
    result=[]
    for p in sc._container(frame+0x1c):
        if p==0: result.append({'kind':'null'});continue
        value=cell_value(sc.o,p)
        if sc.o.read_u32(p)==VAR_VT:
            if p not in locations: raise AssertionError('unidentified lvalue')
            value.update(kind='lvalue',location=locations[p])
        elif sc.o.read_u32(p)==VAL_VT:value.update(kind='value')
        else:raise AssertionError('unknown VM cell vtable')
        result.append(value)
    return result

