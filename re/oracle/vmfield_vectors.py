def main():
    arg = sys.argv[1] if len(sys.argv)>1 else 'gen'
    if arg=='verify':
        selected = [Path(p) for p in sys.argv[2:]]
        paths = selected or [OUT/f'vmfield_{name}.jsonl' for name in GROUPS]
        missing = [str(path) for path in paths if not path.is_file()]
        if missing: raise SystemExit('missing vmfield suites: '+', '.join(missing))
        count = 0
        for path in paths:
            lines = path.read_text().splitlines()
            if not lines: raise SystemExit(f'empty vector file: {path}')
            records = [json.loads(line) for line in lines]
            if not selected:
                name = path.stem.removeprefix('vmfield_')
                expected = len(GROUPS[name][1]())
                if len(records) != expected: raise SystemExit(f'incomplete suite: {path}: {len(records)}/{expected} rows')
                if any(record['name'] != name for record in records): raise SystemExit(f'wrong suite identity: {path}')
            for recorded in records:
                actual=GROUPS[recorded['name']][0](recorded['input'])
                if actual != recorded['result']: raise AssertionError((path,recorded['id'],actual,recorded['result']))
                count += 1
        if count == 0: raise SystemExit('no compared vmfield rows')
        print(f'verify: {count}/{count} identical')
    else:
        OUT.mkdir(parents=True,exist_ok=True)
        names = list(GROUPS) if arg=='gen' else [arg]
        for name in names:
            path=OUT/f'vmfield_{name}.jsonl'
            rows=[row(name,i,case) for i,case in enumerate(GROUPS[name][1]())]
            path.write_text(''.join(json.dumps(value,sort_keys=True)+'\n' for value in rows))
            print(f'{path}: {len(rows)} rows')
