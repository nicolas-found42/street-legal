def stock_trees(relative):
    """Decode TREE bytes only; preserve every shipped node and immediate."""
    data = (stock_path() / relative).read_bytes(); pos = 0; tree = None
    while pos < len(data):
        tag, size = struct.unpack_from('<4sI', data, pos); pos += 8
        if tag == b'TREE': tree = data[pos:pos+size]
        pos += size
    if tree is None: raise ValueError('missing TREE')
    pos = 0
    def u32():
        nonlocal pos
        value, = struct.unpack_from('<I', tree, pos); pos += 4
        return value
    bodies = []
    for _ in range(u32()):
        nodes = []
        for _ in range(u32()):
            op = OPWORDS[tree[pos]]; pos += 1
            line, = struct.unpack_from('<H', tree, pos); pos += 2
            imm = u32() if op & 0xf000 in (0x1000,0x2000,0x4000) else 0
            nodes.append([op,line,imm])
        bodies.append(nodes)
    assert pos == len(tree)
    return bodies

def fbits(value): return struct.unpack('<I', struct.pack('<f',value))[0]

