#!/usr/bin/env python3
"""Static original477e00 PUSH operands -> Rust device profile data.
Reads instructions only; never executes/copies an oracle result or asset vector.
Output consists of the original routine's literal configuration data and CALL
return PCs. Re-run with --out to reproduce native_player_device_tables.rs.
"""
import argparse,hashlib
from pathlib import Path
from oracle import Oracle
ROOT=Path(__file__).resolve().parents[2];EXE=ROOT/'stock/StreetLegal_Redline.bak.exe'
PROFILES=[('KEYBOARD',0x477e30,0x478479),('JOYSTICK',0x4784a8,0x4788f5),('HAMMER',0x478924,0x478cba),('SIDEWINDER',0x478cd4,0x47903e),('DUALSHOCK',0x47906d,0x4794ff),('GENERIC',0x479518,0x4797c4)]
def capture():
 o=Oracle(str(EXE));lines=['// Source literal PUSH operands from original477e00, generated by native_player_device_recover.py.',f'// Original executable SHA256: {hashlib.sha256(EXE.read_bytes()).hexdigest()}', 'use super::{Axis, Mapping};']
 for name,start,end in PROFILES:
  stack=[];axes=[];mappings=[];delta=0
  for i in o.disasm(start,1000):
   if i.address>=end:break
   if i.mnemonic=='inc'and i.op_str=='esi':delta+=1
   if i.mnemonic=='push':
    v=i.op_str
    if v=='esi':stack.append(('device',delta))
    elif v=='ebx':stack.append(('deadzone',0))
    elif v.startswith('0x')or v.isdigit():stack.append(('literal',int(v,0)))
    else:raise ValueError(f'unsupported push {i}')
   if i.mnemonic=='call':
    target=int(i.op_str,0);args=stack[::-1];stack=[]
    if target==0x54d7b0:
     assert len(args)==6 and all(k=='literal'for k,v in args),(name,hex(i.address),args)
     axes.append((i.address+i.size,[v for k,v in args]))
    elif target==0x54d650:
     assert len(args)==7 and args[1][0]=='device',(name,hex(i.address),args)
     assert all(k=='literal'for j,(k,v)in enumerate(args)if j not in [1,3]),args
     assert args[3][0]in ['literal','deadzone'],args
     mappings.append((i.address+i.size,args))
    else:raise ValueError(f'unsupported call {i}')
  assert not stack,(name,stack)
  lines.append(f'pub const {name}_AXES: &[Axis] = &[')
  for pc,args in axes:lines.append('    Axis { pc: 0x%x, values: [%s] },'%(pc,','.join('0x%x'%v for v in args)))
  lines.append('];');lines.append(f'pub const {name}_MAPPINGS: &[Mapping] = &[')
  for pc,args in mappings:
   get=lambda j:args[j][1]
   dead='None'if args[3][0]=='deadzone'else'Some(0x%x)'%get(3)
   lines.append('    Mapping { pc:0x%x, action:0x%x, device_delta:%d, control:0x%x, input_min:%s, input_max:0x%x, output_min:0x%x, output_max:0x%x },'%(pc,get(0),get(1),get(2),dead,get(4),get(5),get(6)))
  lines.append('];')
 return '\n'.join(lines)+'\n'
if __name__=='__main__':
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--out',type=Path,required=True);a=p.parse_args();a.out.write_text(capture())
