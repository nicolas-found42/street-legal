"""Generate `com_tables.py` from the installed i686 MinGW-w64 14 COM headers.

The tables are the single source for COM vtable layouts used by the headless
oracle. They contain only interface/method names, parameter types and names;
no behaviour. Re-run after changing the header set:

    ~/slr-oracle-venv/bin/python re/headless/gen_com_tables.py [include-dir]
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

DEFAULT_INCLUDE = Path(
    "/opt/homebrew/Cellar/mingw-w64/14.0.0_3/toolchain-i686/i686-w64-mingw32/include"
)
WANTED = {
    "d3d9.h": [
        "IDirect3D9",
        "IDirect3DDevice9",
        "IDirect3DSwapChain9",
        "IDirect3DSurface9",
        "IDirect3DVertexBuffer9",
        "IDirect3DIndexBuffer9",
        "IDirect3DTexture9",
        "IDirect3DCubeTexture9",
        "IDirect3DVolumeTexture9",
        "IDirect3DVertexDeclaration9",
        "IDirect3DVertexShader9",
        "IDirect3DPixelShader9",
        "IDirect3DStateBlock9",
        "IDirect3DQuery9",
    ],
    "dinput.h": ["IDirectInput8A", "IDirectInputDevice8A"],
    "dsound.h": [
        "IDirectSound",
        "IDirectSoundBuffer",
        "IDirectSound3DListener",
        "IDirectSound3DBuffer",
        "IDirectSoundNotify",
    ],
}
BLOCK = re.compile(
    r"DECLARE_INTERFACE(?:_IID)?_\(\s*(\w+)\s*,[^{]*\{(.*?)\n\};", re.S
)
METHOD = re.compile(
    r"STDMETHOD(?:_)?\(\s*(?:([^,()]+?)\s*,\s*)?(\w+)\s*\)\s*\((.*?)\)\s*PURE\s*;",
    re.S,
)


def split_params(text):
    text = " ".join(text.split())
    if text == "THIS":
        return []
    if not text.startswith("THIS_"):
        raise ValueError(f"unexpected parameter list: {text!r}")
    text = text[5:].strip()
    params = []
    depth = 0
    current = ""
    for ch in text:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            params.append(current.strip())
            current = ""
        else:
            current += ch
    if current.strip():
        params.append(current.strip())
    result = []
    for index, param in enumerate(params):
        param = re.sub(r"\s*\[\s*\w*\s*\]$", "*", param)
        match = re.fullmatch(r"(.*?[\s*])(\w+)", param)
        if match is None or match.group(1).strip() in ("const", "struct", "enum"):
            # unnamed parameter: the whole text is the type
            ctype, name = param, f"arg{index}"
        else:
            ctype, name = match.group(1), match.group(2)
        ctype = re.sub(r"\s*\*\s*", "*", ctype).strip()
        result.append((ctype, name))
    return result


def main():
    include = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_INCLUDE
    tables = {}
    for header, names in WANTED.items():
        text = (include / header).read_text(errors="replace")
        blocks = {}
        for match in BLOCK.finditer(text):
            blocks.setdefault(match.group(1), match.group(2))
        for name in names:
            if name not in blocks:
                raise SystemExit(f"{name} not found in {header}")
            methods = []
            for m in METHOD.finditer(blocks[name]):
                methods.append((m.group(2), tuple(split_params(m.group(3)))))
            tables[name] = tuple(methods)
    out = Path(__file__).with_name("com_tables.py")
    lines = [
        '"""Generated by gen_com_tables.py from MinGW-w64 14 i686 headers. Do not edit."""',
        "",
        "INTERFACES = {",
    ]
    for name, methods in tables.items():
        lines.append(f"    {name!r}: (")
        for method, params in methods:
            lines.append(f"        ({method!r}, {params!r}),")
        lines.append("    ),")
    lines.append("}")
    out.write_text("\n".join(lines) + "\n")
    for name, methods in tables.items():
        print(name, len(methods))


if __name__ == "__main__":
    main()
