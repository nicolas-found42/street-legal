#!/usr/bin/env python3
"""gen_native.py: emit native_table.h from re/out/native_api.tsv (M0-11).

Each TSV row is class<TAB>name<TAB>sig<TAB>impl-label; the label's trailing
8 hex digits are the impl RVA (= VA under Wine's fixed exe base). Output is
a static C array consumed by re/hook/hook_native.c.
"""
import os
TSV = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "out", "native_api.tsv"))

def main():
    print("/* GENERATED by re/hook/gen_native.py from re/out/native_api.tsv; do not edit. */")
    print("static const native_row g_native_rows[] = {")
    n = 0
    with open(TSV) as f:
        for line in f:
            line = line.rstrip("\n")
            if not line:
                continue
            cls, name, sig, impl = line.split("\t")
            addr = impl.split("_")[-1]
            int(addr, 16)
            esc = lambda s: s.replace("\\", "\\\\").replace('"', '\\"')
            print('    {"%s", "%s", "%s", 0x%s},' % (esc(cls), esc(name), esc(sig), addr))
            n += 1
    print("};")


if __name__ == "__main__":
    main()
