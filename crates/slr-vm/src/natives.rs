//! The native registry: `(class, name, sig) -> impl` (`FUN_00416b00`).
//!
//! Machine model (all `[static]`, machine code read; oracle: Unicorn running
//! the exe's own registrar, `re/oracle/vmclass_vectors.py`, local only):
//!
//! - A record is 6 words: `[+0]` vtable `0x5f08fc`, `[+4]` the JVM context,
//!   `[+8]` the implementation address, `[+0xc]` the interned class name,
//!   `[+0x10]` the interned method name, `[+0x14]` the 3-word signature
//!   record (`[+0]` the raw descriptor, `[+4]` the interned copy,
//!   `[+8]` spare), built by `FUN_0041dc30`.
//! - The hash is `sum(name bytes) * 0x49 + sum(class bytes)` over the
//!   *interned* (copied) strings; the bucket is `hash & 0x7f` into the
//!   `0x62c`-byte registry at `jvm+0xc` (`FUN_0041a370` zeroes it:
//!   `0x80` buckets of 12 bytes `[hash][record][chain]`, then the free
//!   pools at `+0x600`/`+0x614`). Collisions chain (`+8`).
//! - The committed table (`NATIVE_TABLE`, generated by
//!   `re/build_native_table.py` from exe bytes cross-checked against the
//!   Ghidra export) holds the 353 rows visible in the pseudocode export.
//!   7 further `java.io.Controller` registrations exist as binary call sites
//!   (`0x477d22..0x477ddc`, gap `0x477ca6-0x477e00`) with no Ghidra owner;
//!   they are excluded and reported, not invented.
//!
//! The port stores records in a hash map keyed by `(class, name, sig)`;
//! the exe's bucket order is not observable through any ported interface.

use std::collections::HashMap;

/// One native binding: the method identity plus its implementation address.
#[derive(Clone, Debug, PartialEq, Eq, Hash)]
pub struct NativeKey {
    /// `java.game.parts.WheelRef` (dotted, as registered).
    pub class: String,
    /// `getPos`.
    pub name: String,
    /// `()Ljava.lang.Vector3;`.
    pub sig: String,
}

/// One native record: the key plus the exe address of the implementation.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct NativeRecord {
    /// Method identity.
    pub key: NativeKey,
    /// Exe address of the native implementation (`record+8`).
    pub impl_addr: u32,
}

/// The native registry (`jvm+0xc` object, `FUN_0041a370` shape).
///
/// exe: FUN_00416b00
#[derive(Clone, Debug, Default)]
pub struct Natives {
    records: HashMap<NativeKey, NativeRecord>,
}

impl Natives {
    /// An empty registry (matches the `FUN_0041a370` zeroed `0x62c` block).
    ///
    /// exe: FUN_0041a370
    #[must_use]
    pub fn new() -> Self {
        Self::default()
    }

    /// Number of registered natives.
    #[must_use]
    pub fn len(&self) -> usize {
        self.records.len()
    }

    /// `true` when nothing is registered.
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.records.is_empty()
    }

    /// The exe's registrar hash over the interned strings
    /// (`sum(name) * 0x49 + sum(class)`, bytes unsigned).
    ///
    /// exe: FUN_00416b00
    #[must_use]
    pub fn hash(class: &str, name: &str) -> u32 {
        let sum = |s: &str| s.bytes().map(u32::from).sum::<u32>();
        sum(name).wrapping_mul(0x49).wrapping_add(sum(class))
    }

    /// The bucket index (`hash & 0x7f`).
    ///
    /// exe: FUN_00416b00
    #[must_use]
    pub fn bucket(class: &str, name: &str) -> usize {
        (Self::hash(class, name) & 0x7f) as usize
    }

    /// Register one native (`FUN_00416b00`): builds the 6-word record
    /// (always succeeds here; the exe returns 1) and stores it under
    /// `(class, name, sig)`.
    ///
    /// exe: FUN_00416b00
    pub fn register(&mut self, class: &str, name: &str, sig: &str, impl_addr: u32) {
        let key = NativeKey {
            class: class.to_owned(),
            name: name.to_owned(),
            sig: sig.to_owned(),
        };
        self.records
            .insert(key.clone(), NativeRecord { key, impl_addr });
    }

    /// Resolve `(class, name, sig)` to its implementation address, or `None`
    /// (the exe's `FUN_00404910` miss path, a fatal script error upstream).
    #[must_use]
    pub fn resolve(&self, class: &str, name: &str, sig: &str) -> Option<u32> {
        self.records
            .get(&NativeKey {
                class: class.to_owned(),
                name: name.to_owned(),
                sig: sig.to_owned(),
            })
            .map(|r| r.impl_addr)
    }

    /// All records, sorted by `(class, name, sig)` for deterministic tests.
    #[must_use]
    pub fn sorted(&self) -> Vec<&NativeRecord> {
        let mut out: Vec<&NativeRecord> = self.records.values().collect();
        out.sort_by(|a, b| {
            (&a.key.class, &a.key.name, &a.key.sig).cmp(&(&b.key.class, &b.key.name, &b.key.sig))
        });
        out
    }
}

/// The 7 `java.io.Controller` natives registered from the Ghidra function
/// gap (`0x477ca6-0x477e00`, sites `0x477d22..0x477ddc`): present in the exe
/// but ownerless in the export, so excluded from the committed table.
/// Recorded here so the exclusion is explicit, not silent.
pub const CONTROLLER_EXCLUDED: [(&str, &str, &str); 7] = [
    ("java.io.Controller", "user_Add", "(IIIFFFF)I"),
    ("java.io.Controller", "user_Del", "(III)I"),
    ("java.io.Controller", "user_SetAxisSmooth", "(IFFFFF)I"),
    ("java.io.Controller", "user_SetAxisSpeed", "(IF)V"),
    ("java.io.Controller", "user_Reset", "()V"),
    ("java.io.Controller", "user_GetAxisVal", "(I)F"),
    ("java.io.Controller", "user_SetAxisForce", "(IFF)V"),
];

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn hash_matches_exe_rule() {
        // `sum(name)*0x49 + sum(class)`, bytes unsigned (movsx of ASCII).
        let class = "java.game.parts.WheelRef";
        let name = "getPos";
        let want = name.bytes().map(u32::from).sum::<u32>() * 0x49
            + class.bytes().map(u32::from).sum::<u32>();
        assert_eq!(Natives::hash(class, name), want);
        assert_eq!(Natives::bucket(class, name), (want & 0x7f) as usize);
        // Oracle-pinned row from the live probe.
        assert_eq!(Natives::bucket(class, name), 4);
    }

    #[test]
    fn register_then_resolve() {
        let mut n = Natives::new();
        assert!(n.is_empty());
        n.register(
            "java.game.parts.WheelRef",
            "getPos",
            "()Ljava.lang.Vector3;",
            0x0041_b860,
        );
        assert_eq!(n.len(), 1);
        assert_eq!(
            n.resolve(
                "java.game.parts.WheelRef",
                "getPos",
                "()Ljava.lang.Vector3;"
            ),
            Some(0x0041_b860)
        );
        assert_eq!(
            n.resolve("java.game.parts.WheelRef", "getPos", "()V"),
            None,
            "signature is part of the key"
        );
        assert_eq!(
            n.resolve("java.game.Part", "getPos", "()Ljava.lang.Vector3;"),
            None,
            "class is part of the key"
        );
    }

    #[test]
    fn controller_exclusions_are_seven() {
        assert_eq!(CONTROLLER_EXCLUDED.len(), 7);
    }
}
